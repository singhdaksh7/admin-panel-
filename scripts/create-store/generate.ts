import crypto from "node:crypto";

export interface StoreAnswers {
  storeName: string;
  storeSlug: string;
  currency: string;
  locale: string;
  timezone: string;
  paymentProvider: "MOCK" | "MANUAL" | "RAZORPAY";
  shippingProvider: "MANUAL" | "MOCK" | "SHIPROCKET";
  customerAccounts: boolean;
  reviews: boolean;
  blog: boolean;
  coupons: boolean;
  inventory: boolean;
  adminEmail: string;
  /** India GST mode is the only region-specific preset; everything else is generic */
  taxMode: "NONE" | "EXCLUSIVE" | "INCLUSIVE" | "INDIA_GST";
}

export const PAYMENT_PROVIDERS = ["MANUAL", "RAZORPAY", "MOCK"] as const;
export const SHIPPING_PROVIDERS = ["MANUAL", "SHIPROCKET", "MOCK"] as const;

export function slugify(s: string): string {
  return (
    s
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[̀-ͯ]/g, "")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "store"
  );
}

/** Returns an error message or null. */
export function validateAnswers(a: StoreAnswers): string | null {
  if (!a.storeName.trim()) return "Store name is required";
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(a.storeSlug))
    return "Store slug must be lowercase letters, digits and dashes";
  if (!/^[A-Z]{3}$/.test(a.currency)) return "Currency must be a 3-letter ISO code (e.g. USD, INR)";
  try {
    new Intl.DateTimeFormat(a.locale, { timeZone: a.timezone });
  } catch {
    return "Invalid locale or timezone";
  }
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(a.adminEmail)) return "Initial admin email is invalid";
  return null;
}

export function randomSecret(bytes = 32): string {
  return crypto.randomBytes(bytes).toString("hex");
}

function dbName(slug: string) {
  return `commerce_${slug.replace(/-/g, "_")}`;
}

/**
 * Builds a .env for a NEW deployment. Generates a fresh SESSION_SECRET and DB password.
 * Provider secrets are left BLANK with a comment - they must be filled in by the operator.
 * No admin password is ever written (it is supplied at create-admin time).
 */
export function buildEnv(
  a: StoreAnswers,
  opts: { secret?: string; dbPassword?: string } = {},
): string {
  const secret = opts.secret ?? randomSecret();
  const dbPassword = opts.dbPassword ?? randomSecret(16);
  const db = dbName(a.storeSlug);
  const lines = [
    `# Generated by create-store for "${a.storeName}". NEVER commit this file.`,
    `NODE_ENV=production`,
    `PORT=4000`,
    `# Public URL of THIS API (used in links and webhooks)`,
    `PUBLIC_API_URL=https://api.example.com`,
    `POSTGRES_USER=commerce`,
    `POSTGRES_PASSWORD=${dbPassword}`,
    `POSTGRES_DB=${db}`,
    `DATABASE_URL=postgresql://commerce:${dbPassword}@localhost:5432/${db}?schema=public`,
    `# Browser origins allowed to call the API: admin + storefront. No wildcards.`,
    `CORS_ORIGINS=https://admin.example.com,https://www.example.com`,
    `SESSION_SECRET=${secret}`,
    `COOKIE_SECURE=true`,
    `COOKIE_DOMAIN=`,
    `LOG_LEVEL=info`,
    ``,
    `# --- first admin: set the PASSWORD only when running \`npm run create-admin\` ---`,
    `INITIAL_ADMIN_EMAIL=${a.adminEmail}`,
    `INITIAL_ADMIN_PASSWORD=`,
    ``,
    `STORAGE_PROVIDER=LOCAL`,
    `UPLOAD_DIR=/data/uploads`,
    `MAX_UPLOAD_MB=8`,
    ``,
    `PAYMENT_PROVIDER=${a.paymentProvider}`,
    ...(a.paymentProvider === "RAZORPAY"
      ? [`# REQUIRED for RAZORPAY: values from your Razorpay dashboard`]
      : []),
    `RAZORPAY_KEY_ID=`,
    `RAZORPAY_KEY_SECRET=`,
    `RAZORPAY_WEBHOOK_SECRET=`,
    ``,
    `SHIPPING_PROVIDER=${a.shippingProvider}`,
    ...(a.shippingProvider === "SHIPROCKET"
      ? [`# REQUIRED for SHIPROCKET: API user credentials`]
      : []),
    `SHIPROCKET_EMAIL=`,
    `SHIPROCKET_PASSWORD=`,
    ``,
    `# EMAIL_PROVIDER=LOG only logs emails. Switch to SMTP and fill SMTP_* for real delivery.`,
    `EMAIL_PROVIDER=LOG`,
    `SMTP_HOST=`,
    `SMTP_PORT=587`,
    `SMTP_USER=`,
    `SMTP_PASSWORD=`,
    `EMAIL_FROM=no-reply@example.com`,
  ];
  return lines.join("\n") + "\n";
}

/** Non-secret store configuration applied to StoreSettings (by `apply`). */
export function buildStoreConfig(a: StoreAnswers) {
  return {
    store: a.storeSlug,
    settings: {
      name: a.storeName.trim(),
      currency: a.currency,
      locale: a.locale,
      timezone: a.timezone,
      tax: { mode: a.taxMode, defaultRate: a.taxMode === "INDIA_GST" ? 18 : 0 },
      checkout: {
        guestCheckout: true,
        requirePhone: a.taxMode === "INDIA_GST",
        orderPrefix: "ORD",
        invoicePrefix: "INV",
        returnWindowDays: 14,
      },
      features: {
        customerAccounts: a.customerAccounts,
        guestCheckout: true,
        reviews: a.reviews,
        blog: a.blog,
        coupons: a.coupons,
        inventory: a.inventory,
      },
    },
    providers: { payment: a.paymentProvider, shipping: a.shippingProvider },
    adminEmail: a.adminEmail,
  };
}

export function nextSteps(a: StoreAnswers, envFile: string): string {
  const needs: string[] = [];
  if (a.paymentProvider === "RAZORPAY")
    needs.push("RAZORPAY_KEY_ID / RAZORPAY_KEY_SECRET / RAZORPAY_WEBHOOK_SECRET");
  if (a.shippingProvider === "SHIPROCKET") needs.push("SHIPROCKET_EMAIL / SHIPROCKET_PASSWORD");
  return [
    `Next steps for "${a.storeName}":`,
    `  1. Edit ${envFile}: set PUBLIC_API_URL, CORS_ORIGINS${needs.length ? ", " + needs.join(", ") : ""}.`,
    `  2. Create the database and apply migrations:   npm run db:migrate`,
    `  3. Apply the store configuration:               npm run create-store -- --apply store.config.json`,
    `  4. Create the first admin (password via env):   INITIAL_ADMIN_PASSWORD='<strong password>' npm run create-admin`,
    `  5. Start API + Admin (docker-compose.prod.yml.example) and sign in to configure products.`,
    `  See docs/NEW_CLIENT_CHECKLIST.md.`,
  ].join("\n");
}
